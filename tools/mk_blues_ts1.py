#!/usr/bin/env python3
"""Generate the private V45 amp header from the converted Two-Rock A2 Lite."""

import argparse
import json
from pathlib import Path

import numpy as np

import nam_a2
import nam_level
from mk_nam_factory import cfloat


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("capture", type=Path)
    args = parser.parse_args()
    model, channels = nam_a2.pick(json.loads(args.capture.read_text()), "lite")
    if channels != 3 or model.get("sample_rate") != 44100:
        parser.error("expected a 44.1 kHz A2 Lite capture")
    weights = np.asarray(model["weights"], dtype=np.float32)
    if not np.isfinite(weights).all():
        parser.error("capture has non-finite weights")
    trim = nam_level.trim_db(nam_a2.unpack(weights.astype(np.float64), channels))
    lines = [", ".join(cfloat(v) for v in weights[i:i + 10]) for i in range(0, len(weights), 10)]
    folder = Path(__file__).resolve().parents[1] / "build/blues/v45-private"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "px_blues_ts1_private.h").write_text(
        "/* Private Two-Rock TS-1 Edge capture. Generated by tools/mk_blues_ts1.py. */\n"
        f"#define PXN_TS1_TRIM {cfloat(trim)}\n"
        "static const float PXN_TS1_WEIGHTS[PXN_NW] = {\n    " + ",\n    ".join(lines) + "\n};\n"
    )
    print(f"Two-Rock TS-1 Edge: {len(weights)} weights at 44.1 kHz, trim {trim:+.2f} dB")


if __name__ == "__main__":
    main()
